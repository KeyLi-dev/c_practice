// 接收两个double，返回调和平均
double harmonic(double a, double b)
{
    double inv1 = 1.0 / a;
    double inv2 = 1.0 / b;
    double avg_inv = (inv1 + inv2) / 2.0;
    return 1.0 / avg_inv;
}
