/*第7章 编程练习第9题 原题

编写一个程序，只接受正整数输入，然后显示小于或者等于该数的所有素数。

什么是素数（质数）
素数：大于1的自然数，只能被 1 和它本身整除，不能被其他数字整除。
• 2 是素数（只能÷1、÷2），是最小素数

• 3 是素数

• 4 不是素数：4可以被2整除

• 1 不是素数

判断一个数 n 是不是素数思路举例

举例：判断 n =7 是不是素数

1. n必须大于1；7>1，满足。

2. 拿 2 ~ n‑1之间所有整数，依次去除7

◦ 7 ÷2，不能整除

◦ 7 ÷3，不能整除

◦ 7 ÷4，不能整除

◦ 7 ÷5，不能整除

◦ 7 ÷6，不能整除

3. 如果全部都不能整除 → 7是素数。

举例：判断 n=10
拿2去除10，10%2 ==0，可以整除 → 10不是素数。
小优化：不用循环到n‑1，循环到 \sqrt{n} 就够，习题初学直接循环到 n‑1写最简单。
整道题整体逻辑流程

1. 用户输入一个正整数；输入0就退出程序；小于2提示重新输入。

2. 外层循环：从2遍历到用户输入的这个数字，每一个数拿出来检查。

3. 内层循环：判断当前这个数字是不是素数。

4. 如果是素数，打印输出。
举例子：用户输入10
输出：2 3 5 7
你可以按照自己习惯拆分函数，比如写一个is_prime(int num)用来判断是否素数，返回1代表是素数，返回0不是，这样main函数会很清爽。写完可以拿过来我帮你看。*/